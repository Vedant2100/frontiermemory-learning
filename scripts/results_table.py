def interval(ci) -> str:
    lo, hi = ci
    m = lambda x: f"{x:+.2f}".replace("-", "$-$")
    return "unbounded" if lo is None else f"{m(lo)} to {m(hi)}"


def render(a: dict) -> str:
    p, s1, s2 = a["primary"], a["sensitivity_without_no_reference_tasks"], a.get("sensitivity_without_model_unavailable")
    runs = len(a["runs_used"])
    rows = []
    for task, v in sorted(a["per_task"].items(), key=lambda kv: SHORT.get(kv[0], kv[0])):
        (ka, na), (km, nm) = v["A0"], v["HM"]
        rows.append(f"\\raggedright {SHORT.get(task, task)} & {ka}/{na} & {km}/{nm}")
    pa, pm = a["pooled"]["A0"], a["pooled"]["HM"]
    half = (len(rows) + 1) // 2  # two side-by-side blocks keep the table short in a single column
    left, right = rows[:half], rows[half:] + [f"\\textbf{{Pooled}} & {pa['pass']}/{pa['n']} & {pm['pass']}/{pm['n']}"]
    right += [""] * (half - len(right))
    rows = [f"{l} & {r} \\\\" if r else f"{l} & & & \\\\" for l, r in zip(left, right)]
    lines = [
        "% Generated by scripts/results_table.py from results/official/analysis.json. Do not edit by hand.",
        f"\caption{{Strict passes per task: no memory (A0, 3 attempts) and Hermes memory (HM, {runs} runs of 3 attempts).}}",
        "\label{tab:main}",
        "\normalsize",
        "\setlength{\tabcolsep}{2pt}",
        "\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}p{0.38\textwidth}rr@{\hspace{0.5em}}p{0.38\textwidth}rr}",
        "\toprule",
        "Task & A0 & HM & Task & A0 & HM \\",
        "\midrule", *rows, "\bottomrule", "\end{tabular*}", "",
        f"\gdef\resRuns{{{runs}}}",
        f"\gdef\resMeanDiff{{{p['mean_diff']:+.2f}}}",
        f"\gdef\resCI{{{interval(p['ci95'])}}}",
        f"\gdef\resP{{{p['p_one_sided']:.2f}}}",
        f"\gdef\resUp{{{p['tasks_up']}}}", f"\gdef\resDown{{{p['tasks_down']}}}",
        f"\gdef\resSensNoRefP{{{s1['p_one_sided']:.2f}}}",
        f"\gdef\resSensUnavailP{{{s2['p_one_sided']:.2f}}}" if s2 else "\gdef\resSensUnavailP{n/a}",
    ]
    return "\n".join(lines) + "\n"


def self_test() -> None:
    import sys
    sys.path.insert(0, str(REPO / "scripts"))
    import analyze_official as ao
    rows = lambda passes, digest: [{"task": f"letta-ai/{t}", "valid": True, "passed": i < k, "memory_sha256": digest}
                                   for t, k in zip(SHORT, passes) for i in range(3)]
    a = ao.analyse({ao.CONTROL: rows([0] * 15, None), ao.RUNS[0]: rows([1] * 5 + [0] * 10, "abc")})
    out = render(json.loads(json.dumps(a)))
    assert "Pooled} & 0/45 & 5/45" in out and "\\gdef\\resP{0.03}" in out and "\\gdef\\resRuns{1}" in out, out
    assert "\\begin{table*}" not in out and "\\end{table*}" not in out, out
    assert out.count("\\\\") == 8 + 1, out.count("\\\\")
    for label in (
        "APEX Brightpath market-share", "AutomationBench partnership contract",
        "Awilix release-tier (explicit)", "cattrs partial-structuring",
        "HTTPX cookie-store", "Customer-delivery preferences",
        "DAPT intrusion-detection", "EnterpriseOps customer service management",
    ):
        assert label in out, label
    for old in ("APEX market share", "AutoBench", "EntOps CSM", "cookie store"):
        assert old not in out, old
    print("self-test passed")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--analysis", type=Path, default=REPO / "results/official/analysis.json")
    ap.add_argument("--out", type=Path, default=REPO / "paper/sections/generated-results.tex")
    ap.add_argument("--test", action="store_true")
    args = ap.parse_args()
    if args.test:
        return self_test()
    a = json.loads(args.analysis.read_text())
    if "primary" not in a:
        raise SystemExit(f"analysis has no primary result: {a.get('flags')}")
    args.out.write_text(render(a))
    print(f"wrote {args.out}; flags: {a['flags']}")


if __name__ == "__main__":
    main()
