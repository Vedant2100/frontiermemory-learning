"""Write the paper's main results table and headline numbers from results/official/analysis.json.

Output: paper/sections/generated-results.tex, which results.tex \\input s. Only aggregate counts; no trial text.
Usage: python3 -I scripts/results_table.py [--analysis PATH] [--out PATH] [--test]
"""

from __future__ import annotations

import argparse
import json
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SHORT = {"apex-brightpath-market-share": "APEX market share", "apex-brightpath-seat-surplus": "APEX seat surplus",
         "apex-eurogrid-curtailment": "APEX curtailment", "automationbench-marketing-content-gap-analysis": "AutoBench marketing",
         "automationbench-sales-chatgpt-proposal-customization": "AutoBench proposal", "automationbench-sales-partnership-contract": "AutoBench contract",
         "awilix-release-tier-explicit": "awilix explicit", "awilix-release-tier-implicit": "awilix implicit", "build-word2vec-pipeline": "Word2Vec",
         "cattrs-compositional-changelog": "cattrs", "cookie-store-compositional-changelog": "cookie store",
         "customer-delivery-contextual-preferences": "customer delivery", "dapt-intrusion-detection-workflow-learning": "DAPT",
         "enterpriseops-csm-26d1b04a": "EntOps CSM", "enterpriseops-teams-2725d17f": "EntOps teams"}


def interval(ci) -> str:
    lo, hi = ci
    return "unbounded" if lo is None else f"[{lo:+.2f}, {hi:+.2f}]"


def render(a: dict) -> str:
    p, s1, s2 = a["primary"], a["sensitivity_without_no_reference_tasks"], a.get("sensitivity_without_model_unavailable")
    runs = len(a["runs_used"])
    rows = []
    for task, v in sorted(a["per_task"].items(), key=lambda kv: SHORT.get(kv[0], kv[0])):
        (ka, na), (km, nm) = v["A0"], v["HM"]
        rows.append(f"{SHORT.get(task, task)} & {ka}/{na} & {km}/{nm} \\\\")
    pa, pm = a["pooled"]["A0"], a["pooled"]["HM"]
    lines = [
        "% Generated by scripts/results_table.py from results/official/analysis.json. Do not edit by hand.",
        "\\begin{table}[t]", "\\centering",
        f"\\caption{{Strict passes per task: no memory (A0, 3 attempts) and Hermes memory (HM, {runs} run{'s' if runs != 1 else ''} of 3 attempts).}}",
        "\\label{tab:main}", "\\footnotesize", "\\begin{tabular}{@{}lcc@{}}", "\\toprule", "Task & A0 & HM \\\\", "\\midrule", *rows,
        "\\midrule", f"Pooled & {pa['pass']}/{pa['n']} & {pm['pass']}/{pm['n']} \\\\", "\\bottomrule", "\\end{tabular}", "\\end{table}", "",
        f"\\newcommand{{\\resRuns}}{{{runs}}}",
        f"\\newcommand{{\\resMeanDiff}}{{{p['mean_diff']:+.3f}}}",
        f"\\newcommand{{\\resCI}}{{{interval(p['ci95'])}}}",
        f"\\newcommand{{\\resP}}{{{p['p_one_sided']:.3f}}}",
        f"\\newcommand{{\\resUp}}{{{p['tasks_up']}}}", f"\\newcommand{{\\resDown}}{{{p['tasks_down']}}}",
        f"\\newcommand{{\\resSensNoRefP}}{{{s1['p_one_sided']:.3f}}}",
        f"\\newcommand{{\\resSensUnavailP}}{{{s2['p_one_sided']:.3f}}}" if s2 else "\\newcommand{\\resSensUnavailP}{n/a}",
    ]
    return "\n".join(lines) + "\n"


def self_test() -> None:
    import sys
    sys.path.insert(0, str(REPO / "scripts"))
    import analyze_official as ao
    rows = lambda passes, digest: [{"task": f"letta-ai/{t}", "valid": True, "passed": i < k, "memory_sha256": digest}
                                   for t, k in zip(SHORT, passes) for i in range(3)]
    a = ao.analyse({ao.CONTROL: rows([0] * 15, None), ao.RUNS[0]: rows([1] * 5 + [0] * 10, "abc")})
    out = render(json.loads(json.dumps(a)))
    assert "Pooled & 0/45 & 5/45" in out and "\\resP}{0.031}" in out and "\\resRuns}{1}" in out, out
    assert out.count("\\\\") == 15 + 2, out.count("\\\\")
    print("self-test passed")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--analysis", type=Path, default=REPO / "results/official/analysis.json")
    ap.add_argument("--out", type=Path, default=REPO / "paper/sections/generated-results.tex")
    ap.add_argument("--test", action="store_true")
    args = ap.parse_args()
    if args.test:
        return self_test()
    a = json.loads(args.analysis.read_text())
    if "primary" not in a:
        raise SystemExit(f"analysis has no primary result: {a.get('flags')}")
    args.out.write_text(render(a))
    print(f"wrote {args.out}; flags: {a['flags']}")


if __name__ == "__main__":
    main()
